"""Builds config.json from the BCI species CSVs. Run: python build_config.py
Scientific names only (prototype). Subspecies (3-word names) are dropped.
Insects: Quick = first INSECT_QUICK species, Full = all."""
import csv, glob, json

INSECT_QUICK = 50
SPOTS = ["Lab Clearing", "Trail", "Canopy Tower", "Dock"]
FILES = {"Bats": "Bats*.csv", "Birds": "Birds*.csv", "Mammals": "Mammals*.csv", "Insects": "Insects*.csv"}

def load(pattern):
    seen, out = set(), []
    with open(glob.glob(pattern)[0], encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            name = r["ScientificName"].strip()
            if len(name.split()) != 2 or name in seen:
                continue
            seen.add(name)
            out.append({"n": name})
    return sorted(out, key=lambda x: x["n"])

data = {tx: load(p) for tx, p in FILES.items()}
cfg = {
    "title": "iSawIt - BCI",
    "_comment": "Generated by build_config.py from the BCI CSVs (Barro Colorado Island, Panama). Scientific names only (prototype). 'n' = display name. taxa = Quick list; taxaFull = optional full checklist. Insects: Quick holds only the first %d species as a test; the full list (all species in the CSV) is in taxaFull and selectable at session start." % INSECT_QUICK,
    "spots": SPOTS,
    "taxa": {**{k: v for k, v in data.items() if k != "Insects"}, "Insects": data["Insects"][:INSECT_QUICK]},
    "taxaFull": {"Insects": data["Insects"]},
}
with open("config.json", "w", encoding="utf-8") as f:
    json.dump(cfg, f, ensure_ascii=False, indent=1)
print({k: len(v) for k, v in data.items()})
